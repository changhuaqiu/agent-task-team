import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const generatedTypeScript = path.join(root, 'src', 'lib', 'desktop-host', 'generated-build-id.ts');
const generatedRust = path.join(root, 'src-tauri', 'build-id.txt');
const excluded = new Set([
  path.relative(root, generatedTypeScript).replaceAll('\\', '/'),
  path.relative(root, generatedRust).replaceAll('\\', '/'),
]);
const roots = [
  'src',
  'src-tauri',
  'public',
  'scripts/prepare-desktop-build.mjs',
  'scripts/start-desktop-service.mjs',
  'package.json',
  'pnpm-lock.yaml',
  'next.config.ts',
  'tsconfig.json',
];

function collect(relativePath) {
  const normalized = relativePath.replaceAll('\\', '/');
  if (excluded.has(normalized) || normalized.includes('/target/') || normalized.includes('/gen/')) return [];
  const absolute = path.join(root, relativePath);
  const stat = statSync(absolute);
  if (stat.isFile()) return [normalized];
  return readdirSync(absolute)
    .sort((left, right) => left.localeCompare(right))
    .flatMap((entry) => collect(path.join(relativePath, entry)));
}

const hash = createHash('sha256');
for (const relativePath of roots.flatMap(collect).sort((left, right) => left.localeCompare(right))) {
  hash.update(relativePath);
  hash.update('\0');
  hash.update(readFileSync(path.join(root, relativePath)));
  hash.update('\0');
}
const buildId = `desktop-build-${hash.digest('hex').slice(0, 32)}`;
writeFileSync(
  generatedTypeScript,
  `// Generated by scripts/prepare-desktop-build.mjs.\nexport const DESKTOP_BUILD_ID = '${buildId}';\n`,
);
writeFileSync(generatedRust, `${buildId}\n`);
process.stdout.write(`${buildId}\n`);
